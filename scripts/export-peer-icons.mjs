import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import sharp from "sharp";

import { encodePngIco, WINDOWS_ICON_SIZES } from "./lib/icon-export.ts";

const root = NodePath.resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const androidOnly = process.argv.includes("--android");
const unknown = process.argv.slice(2).filter((arg) => arg !== "--check" && arg !== "--android");
if (unknown.length > 0) throw new Error(`Unknown arguments: ${unknown.join(" ")}`);

const mark = await NodeFSP.readFile(NodePath.join(root, "assets/peer/mark.svg"), "utf8");
const paths = mark
  .replace(/^.*?<svg[^>]*>/s, "")
  .replace(/<\/svg>\s*$/, "")
  .trim();
const geometry = [...paths.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
const variants = [
  { directory: "prod", prefix: "black", web: "t3-black-web", background: "#202A27" },
  { directory: "dev", prefix: "blueprint", web: "blueprint-web", background: "#28594C" },
  { directory: "nightly", prefix: "nightly", web: "nightly-web", background: "#343B52" },
];
const foreground = "#FAFCFA";
const outputs = new Map();
const stale = [];

const svg = (body, size = 1024) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${body}</svg>\n`;
const symbol = (x, y, size, color = foreground) =>
  `<g transform="translate(${x} ${y}) scale(${size / 32})" fill="${color}">${paths}</g>`;
const appIcon = (background, mac = false) =>
  svg(
    mac
      ? `<rect x="100" y="100" width="824" height="824" rx="185" fill="${background}"/>${symbol(244, 244, 536)}`
      : `<rect width="1024" height="1024" rx="224" fill="${background}"/>${symbol(192, 192, 640)}`,
  );
const png = (source, size) => sharp(Buffer.from(source)).resize(size, size).png().toBuffer();
const put = (file, data) => outputs.set(file, typeof data === "string" ? Buffer.from(data) : data);
const ico = async (source, sizes) =>
  encodePngIco(
    await Promise.all(sizes.map(async (size) => ({ size, contents: await png(source, size) }))),
  );

if (!androidOnly) {
  put(
    "assets/peer/geometry.ts",
    `// Generated by scripts/export-peer-icons.mjs from mark.svg.\nexport const PEER_MARK_PATHS = [\n${geometry.map((d) => `  ${JSON.stringify(d)},`).join("\n")}\n] as const;\n`,
  );
  put("assets/peer/icon-full.svg", appIcon(variants[0].background));
  put("assets/peer/icon-macos.svg", appIcon(variants[0].background, true));
  put("assets/prod/logo.svg", appIcon(variants[0].background));
  for (const variant of variants) {
    const base = `assets/${variant.directory}`;
    const full = appIcon(variant.background);
    const mac = appIcon(variant.background, true);
    // iOS and Icon Composer apply the platform's own mask.
    const ios = svg(
      `<rect width="1024" height="1024" fill="${variant.background}"/>${symbol(192, 192, 640)}`,
    );
    put(`${base}/${variant.prefix}-ios-1024.png`, await png(ios, 1024));
    put(`${base}/${variant.prefix}-universal-1024.png`, await png(full, 1024));
    put(`${base}/${variant.prefix}-macos-1024.png`, await png(mac, 1024));
    put(`${base}/${variant.web}-apple-touch-180.png`, await png(full, 180));
    put(`${base}/${variant.web}-favicon-16x16.png`, await png(full, 16));
    put(`${base}/${variant.web}-favicon-32x32.png`, await png(full, 32));
    put(`${base}/${variant.web}-favicon.ico`, await ico(full, [16, 32, 48]));
    const windows = variant.directory === "prod" ? "t3-black" : variant.prefix;
    put(`${base}/${windows}-windows.ico`, await ico(full, WINDOWS_ICON_SIZES));

    const color = variant.background
      .slice(1)
      .match(/../g)
      .map((hex) => parseInt(hex, 16) / 255);
    put(`${base}/app-icon.icon/Assets/text.svg`, svg(symbol(24, 24, 80), 128));
    put(
      `${base}/app-icon.icon/icon.json`,
      JSON.stringify(
        {
          fill: { solid: `srgb:${color.map((value) => value.toFixed(5)).join(",")},1.00000` },
          groups: [
            {
              layers: [
                {
                  glass: false,
                  "image-name": "text.svg",
                  name: "Peer mark",
                  position: { scale: 8, "translation-in-points": [0, 0] },
                },
              ],
              shadow: { kind: "neutral", opacity: 0 },
              translucency: { enabled: false, value: 0 },
            },
          ],
          "supported-platforms": { circles: ["watchOS"], squares: "shared" },
        },
        null,
        2,
      ) + "\n",
    );
  }

  const publicFiles = [
    ["favicon.ico", "favicon.ico"],
    ["favicon-16x16.png", "favicon-16x16.png"],
    ["favicon-32x32.png", "favicon-32x32.png"],
    ["apple-touch-180.png", "apple-touch-icon.png"],
  ];
  for (const [suffix, target] of publicFiles) {
    put(`apps/web/public/${target}`, outputs.get(`assets/dev/blueprint-web-${suffix}`));
    put(`apps/marketing/public/${target}`, outputs.get(`assets/prod/t3-black-web-${suffix}`));
  }
  put(
    "apps/marketing/src/assets/icon.webp",
    await sharp(outputs.get("assets/prod/black-macos-1024.png"))
      .webp({ lossless: true })
      .toBuffer(),
  );
  put(
    "apps/marketing/src/assets/icon-nightly.webp",
    await sharp(outputs.get("assets/nightly/nightly-macos-1024.png"))
      .webp({ lossless: true })
      .toBuffer(),
  );
  // The asset name remains stable for the native widget catalog and existing snapshots.
  put("apps/mobile/assets/widget/T3Mark.svg", mark.replace("currentColor", "#000000"));
  for (const channel of ["latest", "nightly"]) {
    const file = `apps/desktop/resources/dmg/dmg-background-${channel}.svg`;
    const original = await NodeFSP.readFile(NodePath.join(root, file), "utf8");
    const color = channel === "latest" ? "#202A27" : foreground;
    const lockup = `<g id="peer-brand">${symbol(28, 15, 36, color)}<text x="72" y="43" fill="${color}" font-family="Helvetica" font-size="24" font-weight="700">Peer</text></g>`;
    put(
      file,
      original.replace(
        /<g id="peer-brand">[\s\S]*?<\/g><text[^>]*>[\s\S]*?<\/text><\/g>|<text x="32" y="44"[^>]*>[\s\S]*?<\/text>/,
        lockup,
      ),
    );
  }
}

// Android's circle mask has radius one third of the canvas; the square mark frame
// fits inside it even at its corners. No baked-in squircle in adaptive artwork.
const androidMark = (size) => symbol(size * 0.275, size * 0.275, size * 0.45, "#FFFFFF");
const adaptive = svg(androidMark(432), 432);
put(
  "apps/mobile/modules/t3-agent-notifications/android/src/main/res/drawable/agent_activity_mark.xml",
  `<!-- Generated from assets/peer/mark.svg by scripts/export-peer-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="32" android:viewportHeight="32">
${geometry.map((d) => `    <path android:fillColor="#FFFFFFFF" android:pathData="${d}" />`).join("\n")}
</vector>
`,
);
put("apps/mobile/assets/android-icon-foreground.png", await png(adaptive, 432));
put("apps/mobile/assets/android-icon-mark.png", await png(adaptive, 432));
put(
  "apps/mobile/assets/android-notification-icon.png",
  await png(svg(symbol(12, 12, 72, "#FFFFFF"), 96), 96),
);
for (const variant of variants) {
  const canvas = (size) => `<rect width="${size}" height="${size}" fill="${variant.background}"/>`;
  if (variant.directory !== "prod") {
    put(
      `apps/mobile/assets/android-icon-background-${variant.directory}.png`,
      await png(svg(canvas(432), 432), 432),
    );
  }
  put(
    `apps/mobile/assets/android-splash-icon-${variant.directory}.png`,
    await png(svg(canvas(1152) + androidMark(1152), 1152), 1152),
  );
}

for (const [file, data] of outputs) {
  const target = NodePath.join(root, file);
  const previous = await NodeFSP.readFile(target).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (previous?.equals(data)) continue;
  if (
    previous &&
    file.endsWith(".json") &&
    JSON.stringify(JSON.parse(previous.toString())) === JSON.stringify(JSON.parse(data.toString()))
  )
    continue;
  if (check) {
    stale.push(file);
  } else {
    await NodeFSP.mkdir(NodePath.dirname(target), { recursive: true });
    await NodeFSP.writeFile(target, data);
    console.log(`wrote ${file}`);
  }
}
if (stale.length > 0) {
  console.error(`Peer brand assets are stale:\n${stale.join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(`${check ? "Verified" : "Generated"} ${outputs.size} Peer brand assets.`);
}
